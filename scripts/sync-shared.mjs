#!/usr/bin/env node
// Copies the Deno-safe parts of the `shared` submodule into supabase/functions/_shared/vendor/shared.
// Why: Supabase's GitHub integration (Preview/branching) bundles Edge Functions from a checkout that
// does NOT include git submodules, so imports pointing into `shared/` fail to resolve.
// shared/ stays the single source of truth; `--check` (run in CI) fails if the copy has drifted.
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "shared", "src");
const out = join(root, "supabase", "functions", "_shared", "vendor", "shared");
if (!existsSync(join(src, "constants.ts"))) {
  console.error("The shared submodule is empty. Run: git submodule update --init");
  process.exit(2);
}
const FILES = ["constants.ts", "time.ts", ...readdirSync(join(src, "schemas")).filter((f) => f.endsWith(".ts")).map((f) => `schemas/${f}`)];
const HEADER = "// GENERATED by scripts/sync-shared.mjs from the `shared` submodule. Do not edit; run `pnpm sync:shared`.\n";

const expected = new Map(FILES.map((f) => [f, HEADER + readFileSync(join(src, f), "utf8")]));

if (process.argv.includes("--check")) {
  const drift = FILES.filter((f) => !existsSync(join(out, f)) || readFileSync(join(out, f), "utf8") !== expected.get(f));
  if (drift.length) { console.error(`Vendored shared code is out of date: ${drift.join(", ")}\nRun: pnpm sync:shared`); process.exit(1); }
  console.log(`Vendored shared code is in sync (${FILES.length} files).`);
} else {
  rmSync(out, { recursive: true, force: true });
  for (const [f, text] of expected) { mkdirSync(dirname(join(out, f)), { recursive: true }); writeFileSync(join(out, f), text); }
  console.log(`Synced ${FILES.length} files to ${out.replace(root + "/", "")}`);
}
